import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { getEnv } from "@/server/env";

/**
 * Private CV storage. The rest of the app only knows about opaque storage keys,
 * so this local-disk implementation can be swapped for private object storage
 * (for example an S3 bucket without public access) without touching callers.
 */
export interface CvStorage {
  /** Stores the file under a new random key and returns that key. */
  save(contents: Uint8Array): Promise<string>;
  /** Returns the file contents, or null when no file exists for the key. */
  read(key: string): Promise<Buffer | null>;
  /** Deletes the file if it exists. */
  remove(key: string): Promise<void>;
}

const STORAGE_KEY_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.pdf$/;

export class LocalCvStorage implements CvStorage {
  private readonly root: string;

  constructor(rootDir: string) {
    this.root = path.resolve(rootDir);
  }

  /**
   * Maps a key to a path inside the storage directory. Keys are generated by
   * the server, but they are still checked so that a bad key (for example
   * "../../etc/passwd") can never reach the file system.
   */
  private pathFor(key: string): string {
    if (!STORAGE_KEY_PATTERN.test(key)) {
      throw new Error("Invalid CV storage key");
    }
    const filePath = path.resolve(this.root, key);
    if (path.dirname(filePath) !== this.root) {
      throw new Error("CV storage key resolves outside the storage directory");
    }
    return filePath;
  }

  async save(contents: Uint8Array): Promise<string> {
    await mkdir(this.root, { recursive: true, mode: 0o700 });
    const key = `${randomUUID()}.pdf`;
    // "wx" refuses to overwrite an existing file; 0600 keeps it owner-only.
    await writeFile(this.pathFor(key), contents, { flag: "wx", mode: 0o600 });
    return key;
  }

  async read(key: string): Promise<Buffer | null> {
    try {
      return await readFile(this.pathFor(key));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw error;
    }
  }

  async remove(key: string): Promise<void> {
    await rm(this.pathFor(key), { force: true });
  }
}

function resolveStorageDir(configuredDir: string): string {
  const storageDir = path.resolve(configuredDir);
  const publicDir = path.resolve("public");
  if (storageDir === publicDir || storageDir.startsWith(publicDir + path.sep)) {
    throw new Error("CV_STORAGE_DIR must be outside the public/ directory");
  }
  return storageDir;
}

let storage: CvStorage | undefined;

export function getCvStorage(): CvStorage {
  storage ??= new LocalCvStorage(resolveStorageDir(getEnv().CV_STORAGE_DIR));
  return storage;
}
